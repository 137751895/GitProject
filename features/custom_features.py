def _lyapunov_numba(arr, window, tau):                              # [新增]
    """李雅普诺夫指数估计"""                                        # [新增]
    n = len(arr)                                                    # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    for i in range(window + tau, n):                                # [新增]
        y = arr[i - window + 1 : i + 1]                             # [新增]
        has_nan = False                                             # [新增]
        for j in range(window):                                     # [新增]
            if np.isnan(y[j]):                                      # [新增]
                has_nan = True                                      # [新增]
                break                                               # [新增]
        if has_nan:                                                 # [新增]
            continue                                                # [新增]
        divergence = 0.0                                            # [新增]
        count = 0                                                   # [新增]
        for j in range(window - tau):                               # [新增]
            min_dist = np.inf                                       # [新增]
            min_idx = -1                                            # [新增]
            for k in range(window - tau):                           # [新增]
                if k == j:                                          # [新增]
                    continue                                        # [新增]
                dist = abs(y[j] - y[k])                             # [新增]
                if dist < min_dist and dist > 0:                    # [新增]
                    min_dist = dist                                 # [新增]
                    min_idx = k                                     # [新增]
            if min_idx >= 0 and j + tau < window and min_idx + tau < window:  # [新增]
                dist_t = abs(y[j + tau] - y[min_idx + tau])         # [新增]
                if min_dist > 0 and dist_t > 0:                    # [新增]
                    divergence += np.log(dist_t / min_dist)         # [新增]
                    count += 1                                      # [新增]
        if count > 0:                                               # [新增]
            result[i] = divergence / (count * tau)                  # [新增]
    return result                                                   # [新增]


def _microstructure_noise_numba(close, window):                     # [新增]
    """微观结构噪声计算"""                                          # [新增]
    n = len(close)                                                  # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    returns = np.zeros(n)                                           # [新增]
    returns[0] = np.nan                                             # [新增]
    for i in range(1, n):                                           # [新增]
        if close[i - 1] > 0:                                       # [新增]
            returns[i] = (close[i] - close[i - 1]) / close[i - 1]  # [新增]
    for i in range(window + 1, n):                                  # [新增]
        cov_sum = 0.0                                               # [新增]
        count = 0                                                   # [新增]
        for j in range(i - window + 1, i + 1):                     # [新增]
            if j > 0 and not np.isnan(returns[j]) and not np.isnan(returns[j - 1]):  # [新增]
                cov_sum += returns[j] * returns[j - 1]              # [新增]
                count += 1                                          # [新增]
        if count > 0 and cov_sum < 0:                               # [新增]
            result[i] = np.sqrt(-cov_sum / count)                   # [新增]
        else:                                                       # [新增]
            result[i] = 0.0                                         # [新增]
    return result                                                   # [新增]


def _price_delay_numba(close, window, max_lag=5):                   # [新增]
    """价格延迟指标计算"""                                          # [新增]
    n = len(close)                                                  # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    returns = np.zeros(n)                                           # [新增]
    returns[0] = np.nan                                             # [新增]
    for i in range(1, n):                                           # [新增]
        if close[i - 1] > 0:                                       # [新增]
            returns[i] = (close[i] - close[i - 1]) / close[i - 1]  # [新增]
    for i in range(window + max_lag, n):                            # [新增]
        y = returns[i - window + 1 : i + 1]                         # [新增]
        has_nan = False                                             # [新增]
        for j in range(window):                                     # [新增]
            if np.isnan(y[j]):                                      # [新增]
                has_nan = True                                      # [新增]
                break                                               # [新增]
        if has_nan:                                                 # [新增]
            continue                                                # [新增]
        Y = y[max_lag:]                                             # [新增]
        n_obs = len(Y)                                              # [新增]
        if n_obs < max_lag + 2:                                     # [新增]
            continue                                                # [新增]
        y_mean = np.mean(Y)                                         # [新增]
        ss_total = np.sum((Y - y_mean) ** 2)                        # [新增]
        if ss_total < 1e-12:                                        # [新增]
            continue                                                # [新增]
        # Simple regression: y_t on y_{t-1}..y_{t-max_lag}         # [新增]
        # Use diagonal approximation for speed                     # [新增]
        ss_res = ss_total                                           # [新增]
        lag_beta_sum = 0.0                                          # [新增]
        for lag in range(1, max_lag + 1):                           # [新增]
            X_lag = y[max_lag - lag : -lag] if lag < len(y) else np.zeros(n_obs)  # [新增]
            X_lag = X_lag[:n_obs]                                   # [新增]
            x_var = np.sum((X_lag - np.mean(X_lag)) ** 2)           # [新增]
            if x_var > 1e-12:                                       # [新增]
                beta = np.sum((X_lag - np.mean(X_lag)) * (Y - y_mean)) / x_var  # [新增]
                lag_beta_sum += beta ** 2                            # [新增]
                ss_res -= beta ** 2 * x_var                         # [新增]
        r2 = max(0, 1 - ss_res / ss_total)                         # [新增]
        if r2 + lag_beta_sum > 0:                                   # [新增]
            result[i] = 1 - r2 / (r2 + lag_beta_sum)               # [新增]
    return result                                                   # [新增]


