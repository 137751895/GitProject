@register_feature(                                                       # [新增]
    group="风险测度", level="level5_cross",                               # [新增]
    description="流动性调整VaR，考虑平仓成本",                          # [新增]
    depends_on=[], output_names=["liquidity_adjusted_var"],              # [新增]
)                                                                        # [新增]
def compute_liquidity_adjusted_var(df, features_df=None, window=50, confidence_level=0.95, **kwargs):  # [新增]
    """流动性调整VaR                                                    # [新增]
    BUGFIX: 使用当前量/中位量比率衡量流动性冲击，避免退化为常数"""      # [新增]
    close = df["close"].values.astype(np.float64)                        # [新增]
    volume = df["volume"].values.astype(np.float64)                      # [新增]
    returns = np.full(len(close), np.nan)                                # [新增]
    for i in range(1, len(close)):                                       # [新增]
        if close[i - 1] > 0:                                            # [新增]
            returns[i] = (close[i] - close[i - 1]) / close[i - 1]       # [新增]
    n = len(returns)                                                     # [新增]
    result = np.full(n, np.nan)                                          # [新增]
    for i in range(window, n):                                           # [新增]
        rw = returns[i - window + 1: i + 1]                              # [新增]
        vw = volume[i - window + 1: i + 1]                               # [新增]
        mask = ~(np.isnan(rw) | np.isnan(vw))                           # [新增]
        if np.sum(mask) < window // 2:                                   # [新增]
            continue                                                     # [新增]
        vr, vv = rw[mask], vw[mask]                                      # [新增]
        sr = np.sort(vr)                                                 # [新增]
        vi = min(int(len(sr) * (1 - confidence_level)), len(sr) - 1)     # [新增]
        var = sr[vi]                                                     # [新增]
        # [BUGFIX] 流动性冲击 = sqrt(median_vol / current_vol)           # [新增]
        cur_v = max(vv[-1], 1e-12)                                       # [新增]
        med_v = max(np.median(vv), 1e-12)                                # [新增]
        liq_cost = 0.01 * np.sqrt(med_v / cur_v)                         # [新增]
        result[i] = var * (1 + liq_cost)                                 # [新增]
    return pd.DataFrame({"liquidity_adjusted_var": result}, index=df.index)  # [新增]


