def _skewness_3rd_numba(returns, window, decay=0.94):              # [新增]
    """加权三阶矩偏度计算"""                                        # [新增]
    n = len(returns)                                                # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    for i in range(window, n):                                      # [新增]
        weights = np.array([decay ** (window - 1 - j) for j in range(window)])  # [新增]
        w_sum = np.sum(weights)                                     # [新增]
        r_win = returns[i - window + 1 : i + 1]                    # [新增]
        has_nan = any(np.isnan(r_win))                              # [新增]
        if has_nan:                                                 # [新增]
            continue                                                # [新增]
        mean = np.sum(weights * r_win) / w_sum                      # [新增]
        dev = r_win - mean                                          # [新增]
        var = np.sum(weights * dev * dev) / w_sum                   # [新增]
        skew = np.sum(weights * dev * dev * dev) / w_sum            # [新增]
        if var > 0:                                                 # [新增]
            result[i] = skew / (var ** 1.5)                         # [新增]
    return result                                                   # [新增]


def _co_skewness_numba(returns, volume, window):                   # [新增]
    """协偏度计算"""                                                # [新增]
    n = len(returns)                                                # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    for i in range(window, n):                                      # [新增]
        r_win = returns[i - window + 1 : i + 1]                    # [新增]
        v_win = volume[i - window + 1 : i + 1]                     # [新增]
        if any(np.isnan(r_win)) or any(np.isnan(v_win)):           # [新增]
            continue                                                # [新增]
        r_mean = np.mean(r_win)                                     # [新增]
        v_mean = np.mean(v_win)                                     # [新增]
        r_dev = r_win - r_mean                                      # [新增]
        v_dev = v_win - v_mean                                      # [新增]
        r_var = np.mean(r_dev * r_dev)                              # [新增]
        v_var = np.mean(v_dev * v_dev)                              # [新增]
        if r_var > 0 and v_var > 0:                                 # [新增]
            r_std = np.sqrt(r_var)                                  # [新增]
            v_std = np.sqrt(v_var)                                  # [新增]
            co_skew = np.mean(r_dev * r_dev * v_dev) / (r_std * r_std * v_std)  # [新增]
            result[i] = co_skew                                     # [新增]
    return result                                                   # [新增]


def _co_kurtosis_numba(returns, volume, window):                   # [新增]
    """协峰度计算"""                                                # [新增]
    n = len(returns)                                                # [新增]
    result = np.full(n, np.nan)                                     # [新增]
    for i in range(window, n):                                      # [新增]
        r_win = returns[i - window + 1 : i + 1]                    # [新增]
        v_win = volume[i - window + 1 : i + 1]                     # [新增]
        if any(np.isnan(r_win)) or any(np.isnan(v_win)):           # [新增]
            continue                                                # [新增]
        r_mean = np.mean(r_win)                                     # [新增]
        v_mean = np.mean(v_win)                                     # [新增]
        r_dev = r_win - r_mean                                      # [新增]
        v_dev = v_win - v_mean                                      # [新增]
        r_var = np.mean(r_dev * r_dev)                              # [新增]
        v_var = np.mean(v_dev * v_dev)                              # [新增]
        if r_var > 0 and v_var > 0:                                 # [新增]
            co_kurt = np.mean(r_dev * r_dev * v_dev * v_dev) / (r_var * v_var)  # [新增]
            result[i] = co_kurt                                     # [新增]
    return result                                                   # [新增]


