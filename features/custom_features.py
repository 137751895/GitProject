    close = df["close"].values.astype(np.float64)                        # [新增]
    n = len(close)                                                       # [新增]
    raw = np.full(n, np.nan)                                             # [新增]
    for i in range(1, n):                                                # [新增]
        if close[i - 1] > 0 and high[i] > low[i]:                       # [新增]
            raw[i] = min(abs(open_[i] - close[i - 1]) / (high[i] - low[i]), 5.0)  # [新增]
