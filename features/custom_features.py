@register_feature(                                                       # [新增]
    group="统计套利", level="level6_transforms",                          # [新增]
    description="配对交易信号，-1卖空，+1买入，0持有",                   # [新增]
    depends_on=["cointegration_residual"],                               # [新增]
    output_names=["pairs_trading_signal"],                               # [新增]
)                                                                        # [新增]
def compute_pairs_trading_signal(df, features_df=None, window=60, entry_threshold=2.0, exit_threshold=0.5, **kwargs):  # [新增]
    """配对交易信号（Z-score触发）                                      # [新增]
    BUGFIX: 平仓使用 abs(z) <= exit_threshold"""                        # [新增]
    if features_df is None or "cointegration_residual" not in features_df.columns:  # [新增]
        return pd.DataFrame({"pairs_trading_signal": np.nan}, index=df.index)  # [新增]
    residual = features_df["cointegration_residual"].values.astype(np.float64)  # [新增]
    n = len(residual)                                                    # [新增]
    result = np.zeros(n)                                                 # [新增]
    position = 0                                                         # [新增]
    for i in range(window, n):                                           # [新增]
        rw = residual[i - window + 1: i + 1]                             # [新增]
        valid = rw[~np.isnan(rw)]                                        # [新增]
        if len(valid) < window // 2 or np.isnan(residual[i]):            # [新增]
            continue                                                     # [新增]
        mean = np.mean(valid)                                            # [新增]
        std = np.std(valid)                                              # [新增]
        if std < 1e-12:                                                  # [新增]
            continue                                                     # [新增]
        z = (residual[i] - mean) / std                                   # [新增]
        if position == 0:                                                # [新增]
            if z > entry_threshold:                                      # [新增]
                position = -1                                            # [新增]
            elif z < -entry_threshold:                                   # [新增]
                position = 1                                             # [新增]
        else:                                                            # [新增]
            if abs(z) <= exit_threshold:  # [BUGFIX]                     # [新增]
                position = 0                                             # [新增]
        result[i] = position                                             # [新增]
    return pd.DataFrame({"pairs_trading_signal": result}, index=df.index)  # [新增]


