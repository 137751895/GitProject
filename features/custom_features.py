def compute_price_discovery_ratio(df, features_df=None, window=20, **kwargs):  # [新增]
    """价格发现比率 = |open - prev_close| / (high - low)"""             # [新增]
    open_ = df["open"].values.astype(np.float64)                         # [新增]
    high = df["high"].values.astype(np.float64)                          # [新增]
