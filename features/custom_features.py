@register_feature(                                                       # [新增]
    group="市场微观结构", level="level4_micro",                           # [新增]
    description="市场效率系数，越接近1越有效",                           # [新增]
    depends_on=[], output_names=["market_microstructure_efficiency"],    # [新增]
)                                                                        # [新增]
def compute_market_microstructure_efficiency(df, features_df=None, window=50, **kwargs):  # [新增]
    """市场效率系数                                                     # [新增]
    BUGFIX: 原报告方差计算未去均值(E[X²]≠Var(X))，修正为正确去均值版本"""  # [新增]
    close = df["close"].values.astype(np.float64)                        # [新增]
    returns = np.full(len(close), np.nan)                                # [新增]
    for i in range(1, len(close)):                                       # [新增]
        if close[i - 1] > 0:                                            # [新增]
            returns[i] = (close[i] - close[i - 1]) / close[i - 1]       # [新增]
    n = len(returns)                                                     # [新增]
    result = np.full(n, np.nan)                                          # [新增]
    for i in range(window, n):                                           # [新增]
        rw = returns[i - window + 1: i + 1]                              # [新增]
        valid = rw[~np.isnan(rw)]                                        # [新增]
        if len(valid) < window // 2:                                     # [新增]
            continue                                                     # [新增]
        # [BUGFIX] 正确去均值方差                                         # [新增]
        var_r = np.var(valid, ddof=0)                                    # [新增]
        # 一阶自协方差                                                    # [新增]
        v_dm = valid - np.mean(valid)                                    # [新增]
        if len(v_dm) < 2:                                                # [新增]
            continue                                                     # [新增]
        cov = np.mean(v_dm[:-1] * v_dm[1:])                              # [新增]
        if abs(cov) > 0:                                                 # [新增]
            eff = var_r / (2 * abs(cov))                                 # [新增]
            result[i] = min(eff, 10.0)                                   # [新增]
    return pd.DataFrame({"market_microstructure_efficiency": result}, index=df.index)  # [新增]


